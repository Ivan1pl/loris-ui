package com.ivan1pl.lorisui.api.component;

/**
 * Direction in which a {@link Panel} arranges its content, in the order the content was added.
 */
public enum Layout {
    /**
     * Places the content side by side, from left to right.
     */
    HORIZONTAL,
    /**
     * Stacks the content from top to bottom. This is the default layout of a panel.
     */
    VERTICAL
}
